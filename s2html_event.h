#ifndef S2HTML_EVENT_H
#define S2HTML_EVENT_H

#include <stdio.h>

/*
 * Maximum number of characters stored for one event.
 */
#define EVENT_DATA_SIZE 1024

/*
 * Parser states.
 *
 * The parser starts in IDLE state.
 * Based on the current character, it moves into
 * the appropriate state.
 */
typedef enum
{
    PSTATE_IDLE,

    PSTATE_PREPROCESSOR,
    PSTATE_RESERVED_KEYWORD,
    PSTATE_IDENTIFIER,
    PSTATE_NUMERIC_CONSTANT,
    PSTATE_STRING,
    PSTATE_ASCII_CHAR,

    PSTATE_SINGLE_LINE_COMMENT,
    PSTATE_MULTI_LINE_COMMENT,

    PSTATE_OPERATOR

} pstate_e;


/*
 * Events generated by the parser.
 *
 * Each event represents one type of C source construct.
 */
typedef enum
{
    PEVENT_NONE,

    PEVENT_PREPROCESSOR,
    PEVENT_RESERVED_KEYWORD,
    PEVENT_IDENTIFIER,
    PEVENT_NUMERIC_CONSTANT,
    PEVENT_STRING,
    PEVENT_ASCII_CHAR,

    PEVENT_SINGLE_LINE_COMMENT,
    PEVENT_MULTI_LINE_COMMENT,

    PEVENT_OPERATOR,
    PEVENT_REGULAR_EXP

} pevent_e;


/*
 * Event structure.
 *
 * type -> tells what kind of C construct was found.
 *
 * data -> contains the actual characters belonging
 *         to that event.
 */
typedef struct
{
    pevent_e type;
    char data[EVENT_DATA_SIZE];

} pevent_t;


/*
 * Initialize parser state.
 */
void parser_init(void);


/*
 * Read source file and generate the next parser event.
 *
 * Returns:
 *     pointer to event when an event is generated
 *     NULL when end of file is reached
 */
pevent_t *get_parser_event(FILE *fd);


/*
 * Get current parser state.
 */
pstate_e get_parser_state(void);

#endif